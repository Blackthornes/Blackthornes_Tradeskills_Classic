-- Blackthornes Tradeskills -- Locale/ruRU.lua
-- Русский (Russian): the words players see, on a Russian client.
--
-- Each line is the English key (exactly as the code writes it) and its
-- Russian. A key with no line here shows in English. The Russian speaks to
-- the player as "ты", in a friendly voice, and uses the game's words
-- (аукцион, ставка, выкуп, рецепт, создать, материалы, распылить,
-- торговец, почтовый ящик, твинк, прибыль). A line may name its values by
-- place ("%2$s ... %1$s") where Russian word order needs it; L.Format puts
-- them in order. Russian has three plural forms; where the code picks
-- between two keys, the second is the form that reads best after most
-- numbers, and many lines read "Label: %d" so any number fits.
--
-- Item, character and skill names stay as the data or the client gives
-- them. tools/check_locale.py lists keys with no line here and lines no
-- longer used.

