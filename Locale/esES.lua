-- Blackthornes Tradeskills -- Locale/esES.lua
-- Spanish: the words players see, on a Spanish client (Spain or Latin America).
--
-- Each line is the English key (exactly as the code writes it) and its
-- Spanish. A key with no line here shows in English. The Spanish is neutral,
-- so it reads well in Spain and Latin America, speaks to the player as
-- "tú" (never "vosotros"), and uses the game's words (casa de subastas,
-- puja, compra directa, receta, fabricar, materiales, desencantar,
-- vendedor, buzón, alter, ganancia). A line may name its values by place
-- ("%2$s ... %1$s") where Spanish word order needs it; L.Format puts them
-- in order.
--
-- Item, character and skill names stay as the data or the client gives
-- them. tools/check_locale.py lists keys with no line here and lines no
-- longer used.

local _, ns = ...
local L = ns.L

local ok, locale = pcall(function() return GetLocale() end)
if not (ok and (locale == "esES" or locale == "esMX")) then return end


